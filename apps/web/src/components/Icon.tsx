export type IconName = (typeof ICON_NAMES)[number]

const byFile = Object.fromEntries(
  Object.entries(raw).map(([path, svg]) => [path.split('/').pop()!.replace('.svg', ''), svg]),
)

if (import.meta.env.DEV) {
  const missing = ICON_NAMES.filter((n) => !byFile[n])
  if (missing.length)
    console.warn(`Icon files missing from the glob/package: ${missing.join(', ')}`)
}

/** The raw SVG markup, for code that builds DOM by hand (the editor's photo widgets). */
export const iconSvg = (name: IconName) => byFile[name] ?? ''

export function Icon({
  name,
  filled = false,
  className,
}: {
  name: IconName
  filled?: boolean
  className?: string
}) {
  const svg = byFile[filled ? `${name}-fill` : name] ?? byFile[name] ?? ''
  return (
    <span
      aria-hidden="true"
      className={cn(
        'inline-flex size-6 shrink-0 [&>svg]:size-full [&>svg]:fill-current',
        className,
      )}
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  )
}
