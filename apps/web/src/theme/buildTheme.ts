import {
  DynamicScheme,
  Hct,
  MaterialDynamicColors,
  TonalPalette,
  Variant,
  argbFromHex,
  hexFromArgb,
} from '@material/material-color-utilities'

/** The one place the look is decided (SPEC 6a): change the seed and run `npm run theme -w @cairn/web`. */
export const SEED = '#7B7B45'

// The library's default tonal-spot chroma (36+) turns lime-ish from this seed, so the palettes are
// set by hand: a muted primary, a quieter secondary, a warm clay tertiary, and warm-tinted neutrals.
const PRIMARY_CHROMA = 25
const SECONDARY_CHROMA = 10
const TERTIARY = { hue: 55, chroma: 24 }
const NEUTRAL_CHROMA = 4
const NEUTRAL_VARIANT_CHROMA = 8

type Role = keyof typeof ROLES
const D = MaterialDynamicColors
const ROLES = {
  background: D.background,
  onBackground: D.onBackground,
  surface: D.surface,
  surfaceDim: D.surfaceDim,
  surfaceBright: D.surfaceBright,
  surfaceContainerLowest: D.surfaceContainerLowest,
  surfaceContainerLow: D.surfaceContainerLow,
  surfaceContainer: D.surfaceContainer,
  surfaceContainerHigh: D.surfaceContainerHigh,
  surfaceContainerHighest: D.surfaceContainerHighest,
  onSurface: D.onSurface,
  surfaceVariant: D.surfaceVariant,
  onSurfaceVariant: D.onSurfaceVariant,
  outline: D.outline,
  outlineVariant: D.outlineVariant,
  inverseSurface: D.inverseSurface,
  inverseOnSurface: D.inverseOnSurface,
  inversePrimary: D.inversePrimary,
  primary: D.primary,
  onPrimary: D.onPrimary,
  primaryContainer: D.primaryContainer,
  onPrimaryContainer: D.onPrimaryContainer,
  secondary: D.secondary,
  onSecondary: D.onSecondary,
  secondaryContainer: D.secondaryContainer,
  onSecondaryContainer: D.onSecondaryContainer,
  tertiary: D.tertiary,
  onTertiary: D.onTertiary,
  tertiaryContainer: D.tertiaryContainer,
  onTertiaryContainer: D.onTertiaryContainer,
  error: D.error,
  onError: D.onError,
  errorContainer: D.errorContainer,
  onErrorContainer: D.onErrorContainer,
  scrim: D.scrim,
  shadow: D.shadow,
} as const

export type Palette = Record<Role, string>
export interface Theme {
  seed: string
  light: Palette
  dark: Palette
}

function scheme(seed: string, isDark: boolean) {
  const sourceColorHct = Hct.fromInt(argbFromHex(seed))
  const hue = sourceColorHct.hue
  return new DynamicScheme({
    sourceColorHct,
    variant: Variant.TONAL_SPOT,
    contrastLevel: 0,
    isDark,
    primaryPalette: TonalPalette.fromHueAndChroma(hue, PRIMARY_CHROMA),
    secondaryPalette: TonalPalette.fromHueAndChroma(hue, SECONDARY_CHROMA),
    tertiaryPalette: TonalPalette.fromHueAndChroma(TERTIARY.hue, TERTIARY.chroma),
    neutralPalette: TonalPalette.fromHueAndChroma(hue, NEUTRAL_CHROMA),
    neutralVariantPalette: TonalPalette.fromHueAndChroma(hue, NEUTRAL_VARIANT_CHROMA),
  })
}

function palette(seed: string, isDark: boolean): Palette {
  const s = scheme(seed, isDark)
  return Object.fromEntries(
    Object.entries(ROLES).map(([name, color]) => [name, hexFromArgb(color.getArgb(s))]),
  ) as Palette
}

export function buildTheme(seed = SEED): Theme {
  return { seed, light: palette(seed, false), dark: palette(seed, true) }
}

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)

function vars(p: Palette, indent: string) {
  return Object.entries(p)
    .map(([role, hex]) => `${indent}--md-${kebab(role)}: ${hex};`)
    .join('\n')
}

/**
 * theme.css: M3 role variables. Light by default, dark under prefers-color-scheme, and either one
 * forced by `data-theme` on <html> (the Settings choice; "system" removes the attribute).
 */
export function themeCss(t: Theme): string {
  return `/* Generated by src/theme/generate.ts from seed ${t.seed}. Do not edit; change the seed and re-run. */
:root {
  color-scheme: light dark;
${vars(t.light, '  ')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${vars(t.dark, '    ')}
  }
}

:root[data-theme='light'] {
  color-scheme: light;
}

:root[data-theme='dark'] {
  color-scheme: dark;
${vars(t.dark, '  ')}
}
`
}

// ---- WCAG contrast, used by the test and handy when tuning the palettes ----

function luminance(hex: string) {
  const [r, g, b] = [1, 3, 5].map((i) => {
    const c = parseInt(hex.slice(i, i + 2), 16) / 255
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4
  }) as [number, number, number]
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}

export function contrast(a: string, b: string): number {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x) as [number, number]
  return (hi + 0.05) / (lo + 0.05)
}
